"""SurprisingVote"""

def main():
    """หาความเป็นไปได้ของคะแนนที่ต่ำสุด โดยตีไปว่าจะมีคนที่ได้คะแนนสูงสุด 2 คน 
    แล้วนำมาลบกับคะแนนทั้งหมดจะได้คะแนนต่ำสุดที่เป็นไปได้ และถ้ามันต่ำกว่า 0 ให้เปลี่ยนเป็น 0 แล้วนำไปลบคะแนนสูงสุด 
    จะได้ความต่างของคะแนนสูงสุดและต่ำสุด"""
    num = float(input())
    h = float(input())

    l = num - (h * 2)
    if l < 0:
        l = 0
    gab = h - l

    if gab <= 2:
        print("Not surprising")
    else:
        print("Surprising")

main()
