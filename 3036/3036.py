"""ปราสาท"""

import math

def main():
    """หาแพทเทิร์นรูปแบบของการคำนวณ และต้องหาให้ได้ว่า n อยู่ในชั้นที่เท่าไหร่ของปราสาท
    และหาว่า n อยู่ในตำแหน่งที่เท่าไหร่ของชั้นนั้น 
    เมื่อได้มาก็นำมาดูว่ามันเป็นตำแหน่งที่เป็นเลขคู่ของคี่ 
    และจะได้คำตอบออกมา"""
    n = int(input())

    a = math.ceil(math.sqrt(n))
    position = n - (a - 1) ** 2

    if position % 2 == 1:
        print((a - 1) * 2)
    else:
        print((a - 1) * 2 - 1)

main()
